interface VS_WiFi_Adapter_Interface {
	/**
	 * Verify network connection for employee check-in or check-out.
	 *
	 * @param object $employee Employee record.
	 * @param array  $payload Verification payload parameters (token, ip, mac, bssid, etc).
	 * @param object $wifi_config Wi-Fi configuration object.
	 * @return array Verification result array (status => bool, code => string, message => string).
	 */
	public function verify( $employee, $payload, $wifi_config );
}

class VS_WiFi_HMAC_Adapter implements VS_WiFi_Adapter_Interface {

	/**
	 * Verify HMAC Signed Wi-Fi Token generated by network portal or router controller.
	 */
	public function verify( $employee, $payload, $wifi_config ) {
		$token     = isset( $payload['token'] ) ? sanitize_text_field( $payload['token'] ) : '';
		$timestamp = isset( $payload['timestamp'] ) ? absint( $payload['timestamp'] ) : 0;
		$ssid      = isset( $payload['ssid'] ) ? sanitize_text_field( $payload['ssid'] ) : '';
		$bssid     = isset( $payload['bssid'] ) ? sanitize_text_field( $payload['bssid'] ) : '';

		if ( empty( $token ) || empty( $timestamp ) ) {
			return array(
				'success' => false,
				'code'    => 'missing_token',
				'message' => __( 'Missing network verification token or timestamp.', 'verification-system' ),
			);
		}

		// Replay Attack Protection: Token must be within configured expiration limit (default 180s)
		$timeout = ! empty( $wifi_config->verification_timeout ) ? absint( $wifi_config->verification_timeout ) : 180;
		if ( abs( time() - $timestamp ) > $timeout ) {
			return array(
				'success' => false,
				'code'    => 'token_expired',
				'message' => __( 'Network verification token has expired or system clock is out of sync.', 'verification-system' ),
			);
		}

		// Validate SSID matches configuration
		if ( ! empty( $wifi_config->ssid ) && strcasecmp( $ssid, $wifi_config->ssid ) !== 0 ) {
			return array(
				'success' => false,
				'code'    => 'invalid_ssid',
				'message' => sprintf( __( 'Connected Wi-Fi (%s) does not match the approved branch workplace network (%s).', 'verification-system' ), $ssid, $wifi_config->ssid ),
			);
		}

		// Validate Multi-AP BSSID list if specified
		if ( ! empty( $wifi_config->allowed_bssids ) && ! empty( $bssid ) ) {
			$allowed = array_map( 'trim', explode( "\n", strtolower( $wifi_config->allowed_bssids ) ) );
			if ( ! in_array( strtolower( $bssid ), $allowed, true ) ) {
				return array(
					'success' => false,
					'code'    => 'invalid_bssid',
					'message' => sprintf( __( 'Connected Access Point BSSID (%s) is not in the approved branch access point list.', 'verification-system' ), $bssid ),
				);
			}
		}

		// Validate HMAC signature
		$secret           = $wifi_config->shared_secret;
		$expected_payload = $employee->id . '|' . $ssid . '|' . $bssid . '|' . $timestamp;
		$expected_hash    = hash_hmac( 'sha256', $expected_payload, $secret );

		if ( ! hash_equals( $expected_hash, $token ) ) {
			return array(
				'success' => false,
				'code'    => 'invalid_signature',
				'message' => __( 'Cryptographic verification failed: Forged or altered network verification token.', 'verification-system' ),
			);
		}

		return array(
			'success' => true,
			'code'    => 'verified',
			'message' => __( 'Successfully verified workplace Wi-Fi connectivity.', 'verification-system' ),
		);
	}
}

class VS_WiFi_Meraki_Adapter implements VS_WiFi_Adapter_Interface {

	/**
	 * Verify association using Cisco Meraki Controller API.
	 */
	public function verify( $employee, $payload, $wifi_config ) {
		$client_ip = isset( $payload['client_ip'] ) ? sanitize_text_field( $payload['client_ip'] ) : '';
		$api_key   = $wifi_config->api_key;
		$endpoint  = $wifi_config->api_endpoint;

		if ( empty( $client_ip ) || empty( $api_key ) || empty( $endpoint ) ) {
			return array(
				'success' => false,
				'code'    => 'config_error',
				'message' => __( 'Meraki API endpoint or secret key is not configured.', 'verification-system' ),
			);
		}

		$response = wp_remote_get( rtrim( $endpoint, '/' ) . '/clients/' . urlencode( $client_ip ), array(
			'headers' => array(
				'X-Cisco-Meraki-API-Key' => $api_key,
				'Accept'                 => 'application/json',
			),
			'timeout' => 5,
		) );

		if ( is_wp_error( $response ) ) {
			return array(
				'success' => false,
				'code'    => 'api_unreachable',
				'message' => __( 'Unable to contact Cisco Meraki network controller.', 'verification-system' ),
			);
		}

		$body = json_decode( wp_remote_retrieve_body( $response ), true );
		if ( isset( $body['ssid'] ) && strcasecmp( $body['ssid'], $wifi_config->ssid ) === 0 ) {
			return array(
				'success' => true,
				'code'    => 'verified',
				'message' => __( 'Verified via Cisco Meraki Enterprise Controller.', 'verification-system' ),
			);
		}

		return array(
			'success' => false,
			'code'    => 'client_not_found',
			'message' => __( 'Device is not associated with the approved workplace Wi-Fi network according to Cisco Meraki API.', 'verification-system' ),
		);
	}
}

class VS_WiFi {

	/**
	 * Perform Wi-Fi verification fail-closed.
	 *
	 * @param object $employee Employee object.
	 * @param array  $payload Verification parameters from client request.
	 * @param bool   $exception_override Administrative override flag.
	 * @return array Verification status array.
	 */
	public static function verify_connection( $employee, $payload, $exception_override = false ) {
		global $wpdb;

		// 1. If exception override is requested by an authorized manager
		if ( $exception_override ) {
			if ( current_user_can( 'administrator' ) || VS_Roles::is_general_manager() || VS_Roles::is_branch_manager() ) {
				self::log_verification( $employee->id, $employee->branch_id, 'OVERRIDE', 'SUCCESS', 'Administrative override granted.', $payload );
				return array(
					'success' => true,
					'code'    => 'admin_override',
					'message' => __( 'Attendance approved via Administrative Exception Override.', 'verification-system' ),
				);
			}
		}

		// 2. Fetch Wi-Fi configuration for branch
		$config_table = $wpdb->prefix . 'vs_wifi_configs';
		$wifi_config  = $wpdb->get_row(
			$wpdb->prepare( "SELECT * FROM {$config_table} WHERE branch_id = %d AND is_active = 1 LIMIT 1", $employee->branch_id )
		);

		if ( ! $wifi_config ) {
			self::log_verification( $employee->id, $employee->branch_id, '', 'FAILED', 'No active Wi-Fi configuration found for this branch.', $payload );
			return array(
				'success' => false,
				'code'    => 'not_configured',
				'message' => __( 'Workplace Wi-Fi verification is not configured for your assigned branch.', 'verification-system' ),
			);
		}

		// 3. Resolve appropriate Adapter
		$adapter = null;
		switch ( $wifi_config->auth_type ) {
			case 'meraki':
				$adapter = new VS_WiFi_Meraki_Adapter();
				break;
			case 'hmac_token':
			default:
				$adapter = new VS_WiFi_HMAC_Adapter();
				break;
		}

		$result = $adapter->verify( $employee, $payload, $wifi_config );

		// 4. Update last successful verification timestamp on success
		if ( $result['success'] ) {
			$wpdb->update(
				$config_table,
				array( 'last_verification' => current_time( 'mysql' ) ),
				array( 'id' => $wifi_config->id )
			);
		}

		// 5. Log verification outcome
		self::log_verification(
			$employee->id,
			$employee->branch_id,
			$wifi_config->ssid,
			$result['success'] ? 'SUCCESS' : 'FAILED',
			$result['message'],
			$payload
		);

		return $result;
	}

	/**
	 * Test network controller connectivity for administrative diagnostics.
	 *
	 * @param int $branch_id Branch ID.
	 * @return array Diagnostic test result.
	 */
	public static function test_controller_connection( $branch_id ) {
		global $wpdb;

		$config_table = $wpdb->prefix . 'vs_wifi_configs';
		$wifi_config  = $wpdb->get_row(
			$wpdb->prepare( "SELECT * FROM {$config_table} WHERE branch_id = %d LIMIT 1", $branch_id )
		);

		if ( ! $wifi_config ) {
			return array(
				'success' => false,
				'message' => __( 'No Wi-Fi configuration saved for this branch.', 'verification-system' ),
			);
		}

		if ( 'meraki' === $wifi_config->auth_type ) {
			if ( empty( $wifi_config->api_endpoint ) || empty( $wifi_config->api_key ) ) {
				return array(
					'success' => false,
					'message' => __( 'Cisco Meraki API endpoint or API key is missing.', 'verification-system' ),
				);
			}

			$response = wp_remote_get( rtrim( $wifi_config->api_endpoint, '/' ) . '/organizations', array(
				'headers' => array( 'X-Cisco-Meraki-API-Key' => $wifi_config->api_key ),
				'timeout' => 5,
			) );

			if ( is_wp_error( $response ) ) {
				return array(
					'success' => false,
					'message' => __( 'Failed to reach Cisco Meraki controller: ', 'verification-system' ) . $response->get_error_message(),
				);
			}

			$code = wp_remote_retrieve_response_code( $response );
			if ( $code >= 200 && $code < 300 ) {
				return array(
					'success' => true,
					'message' => __( 'Cisco Meraki Network Controller is online and authenticated.', 'verification-system' ),
				);
			}

			return array(
				'success' => false,
				'message' => sprintf( __( 'Controller returned HTTP status code %d.', 'verification-system' ), $code ),
			);
		}

		// HMAC Token Mode Diagnostic
		if ( empty( $wifi_config->shared_secret ) ) {
			return array(
				'success' => false,
				'message' => __( 'Shared secret key is required for HMAC Token mode.', 'verification-system' ),
			);
		}

		return array(
			'success' => true,
			'message' => __( 'HMAC Token Verification Engine is active and ready for branch SSID: ', 'verification-system' ) . $wifi_config->ssid,
		);
	}

	/**
	 * Save verification attempt log.
	 */
	private static function log_verification( $employee_id, $branch_id, $ssid, $status, $reason, $payload ) {
		global $wpdb;

		$table = $wpdb->prefix . 'vs_wifi_logs';
		$bssid = isset( $payload['bssid'] ) ? sanitize_text_field( $payload['bssid'] ) : '';
		$ip    = isset( $payload['client_ip'] ) ? sanitize_text_field( $payload['client_ip'] ) : ( isset( $_SERVER['REMOTE_ADDR'] ) ? sanitize_text_field( $_SERVER['REMOTE_ADDR'] ) : '' );

		$wpdb->insert(
			$table,
			array(
				'employee_id'         => $employee_id,
				'branch_id'           => $branch_id,
				'ssid'                => $ssid,
				'bssid'               => $bssid,
				'client_ip'           => $ip,
				'verification_status' => $status,
				'failure_reason'      => $reason,
				'raw_payload'         => wp_json_encode( $payload ),
				'created_at'          => current_time( 'mysql' ),
			)
		);
	}
}
